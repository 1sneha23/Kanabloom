// Generates supabase/seed.sql from src/content/*. Run: npm run gen:seed
// Fails loudly if any content contains Kanji.
import { writeFileSync } from 'node:fs';
import { HIRAGANA, KATAKANA } from '../src/content/kana';
import { LESSONS, QUIZZES } from '../src/content/lessons';
import strokes from '../src/content/kana-strokes.json' with { type: 'json' };
import { findKanji, formatViolations } from '../src/lib/kanji';
import { referenceFromPaths } from '../src/lib/strokes';

const S = strokes as Record<string, string[]>;
const v = findKanji({ HIRAGANA, KATAKANA, LESSONS, QUIZZES });
if (v.length) { console.error(formatViolations(v)); process.exit(1); }

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;

let sql = `-- GENERATED by scripts/gen-seed.ts — do not edit by hand.
-- Stroke data derived from KanjiVG (c) Ulrich Apel, CC BY-SA 3.0 — https://kanjivg.tagaini.net
begin;
`;
for (const [script, list] of [['hiragana', HIRAGANA], ['katakana', KATAKANA]] as const) {
  list.forEach((k, i) => {
    const paths = S[k.char];
    sql += `insert into public.characters (script, char, romaji, row_label, sort_order, pronunciation, example_word, example_romaji, example_meaning, stroke_count, stroke_paths, stroke_points, status)
values ('${script}', ${q(k.char)}, ${q(k.romaji)}, ${q(k.row)}, ${i + 1}, ${q(k.pronunciation)}, ${q(k.example.word)}, ${q(k.example.romaji)}, ${q(k.example.meaning)}, ${paths.length}, ${j(paths)}, ${j(referenceFromPaths(paths))}, 'published')
on conflict (script, char) do nothing;
`;
  });
}
for (const l of LESSONS) {
  sql += `insert into public.lessons (slug, module, title, summary, content, sort_order, status)
values (${q(l.slug)}, '${l.module}', ${q(l.title)}, ${q(l.summary)}, ${j(l.content)}, ${l.sort_order}, 'published')
on conflict (slug) do nothing;
`;
}
for (const z of QUIZZES) {
  sql += `insert into public.quizzes (slug, module, lesson_id, title, questions, status)
values (${q(z.slug)}, '${z.module}', ${z.lesson_slug ? `(select id from public.lessons where slug = ${q(z.lesson_slug)})` : 'null'}, ${q(z.title)}, ${j(z.questions)}, 'published')
on conflict (slug) do nothing;
`;
}
sql += 'commit;\n';
writeFileSync('supabase/seed.sql', sql);
console.log('seed.sql written:', HIRAGANA.length + KATAKANA.length, 'characters,', LESSONS.length, 'lessons,', QUIZZES.length, 'quizzes');
