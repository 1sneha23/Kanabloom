// This file is the input to scripts/gen-seed.ts, which writes supabase/seed.sql.
// At runtime the app reads characters from the database, never from this file.
// Everything here is checked by the no-Kanji validator in tests.

export interface KanaSeed {
  char: string;
  romaji: string;
  row: string;            // gojūon row label, e.g. "a", "ka"
  pronunciation: string;  // plain-English pronunciation hint
  example: { word: string; romaji: string; meaning: string };
}

const p = (
  char: string, romaji: string, row: string, pronunciation: string,
  word: string, wRomaji: string, meaning: string,
): KanaSeed => ({ char, romaji, row, pronunciation, example: { word, romaji: wRomaji, meaning } });

